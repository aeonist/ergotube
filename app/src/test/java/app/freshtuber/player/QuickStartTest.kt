package app.freshtuber.player

import app.freshtuber.innertube.parse.PlayerResponseParser
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonObject
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test
import java.util.zip.GZIPInputStream
import javax.xml.parsers.DocumentBuilderFactory

class QuickStartTest {

    private fun response(): JsonObject {
        val stream = checkNotNull(javaClass.getResourceAsStream("/innertube/player_visionos.json.gz"))
        return Json.parseToJsonElement(GZIPInputStream(stream).bufferedReader().readText()) as JsonObject
    }

    @Test
    fun `player response gives streams with byte ranges, captions and preview frames`() {
        val parsed = PlayerResponseParser.parse(response())
        assertEquals("OK", parsed.status)
        assertEquals("dQw4w9WgXcQ", parsed.videoId)
        assertEquals("UCuAXFkgsw1L7xaCfnd5JJOw", parsed.channelId)
        assertEquals(213L, parsed.lengthSeconds)
        assertFalse(parsed.isLive)
        val avc1080 = parsed.adaptive.first { it.itag == 137 }
        assertEquals("video/mp4", avc1080.mimeType)
        assertEquals("avc1.640028", avc1080.codecs)
        assertEquals(1920, avc1080.width)
        assertEquals(1080, avc1080.height)
        assertEquals(0L, avc1080.initRange!!.start)
        assertEquals(741L, avc1080.initRange!!.end)
        assertEquals(742L, avc1080.indexRange!!.start)
        val opus = parsed.adaptive.first { it.itag == 251 }
        assertTrue(opus.isAudio)
        assertEquals("opus", opus.codecs)
        assertEquals(6, parsed.captions.size)
        assertEquals(1, parsed.captions.count { it.autoGenerated })
        // Level 0 has no interval and is skipped, like NewPipeExtractor does.
        assertEquals(listOf(80, 160), parsed.storyboards.map { it.frameWidth })
        val big = parsed.storyboards[1]
        assertEquals(5, big.urls.size)
        assertTrue(big.urls[0].contains("storyboard3_L2/M0.jpg"))
        assertTrue(big.urls[4].contains("/M4.jpg"))
        assertTrue(big.urls[0].contains("&sigh="))
        assertEquals(2000, big.frameMs)
    }

    @Test
    fun `quick start turns the answer into playable streams with the playback nonce`() {
        val video = QuickStart.resolved(PlayerResponseParser.parse(response()), "dQw4w9WgXcQ", "CPN123", canDecode = { true })
        assertNotNull(video)
        video!!
        assertFalse(video.complete)
        assertEquals(213L, video.durationSeconds)
        assertTrue(video.durationMs in 212_000L..214_000L)
        assertEquals("UCuAXFkgsw1L7xaCfnd5JJOw", video.channel?.id)
        assertTrue(video.videoCandidates.all { it.url.endsWith("&cpn=CPN123") && it.ranges != null && it.itag > 0 })
        // The original track at the highest bitrate: opus 251.
        assertEquals(251, video.audio?.itag)
        assertEquals(video.audioUrl, video.audio?.url)
        assertEquals(6, video.subtitles.size)
        assertTrue(video.subtitles.all { it.url.endsWith("&fmt=ttml") && it.mimeType == "application/ttml+xml" })
        assertTrue(video.subtitles.last().autoGenerated)
        assertEquals(160, video.storyboard?.frameWidth)
    }

    @Test
    fun `quick start leaves anything unusual to the full extraction`() {
        val base = PlayerResponseParser.parse(response())
        assertNull(QuickStart.resolved(base.copy(status = "LOGIN_REQUIRED"), "dQw4w9WgXcQ", "c") { true })
        assertNull(QuickStart.resolved(base.copy(isLive = true), "dQw4w9WgXcQ", "c") { true })
        assertNull(QuickStart.resolved(base, "otherVideo1", "c") { true })
        val throttled = base.copy(adaptive = base.adaptive.map { it.copy(url = it.url + "&n=abc") })
        assertNull(QuickStart.resolved(throttled, "dQw4w9WgXcQ", "c") { true })
        // Without a decoder for VP9 only H.264 streams are offered.
        val noVp9 = QuickStart.resolved(base, "dQw4w9WgXcQ", "c") { it != StreamChoice.VP9 }!!
        assertTrue(noVp9.videoCandidates.isNotEmpty() && noVp9.videoCandidates.none { it.codecMime == StreamChoice.VP9 })
    }

    @Test
    fun `VP9 first when it is decoded in hardware`() {
        val video = QuickStart.resolved(PlayerResponseParser.parse(response()), "dQw4w9WgXcQ", "c") { true }!!
        val avcFirst = StreamChoice.videoTracks(video.videoCandidates)
        val vp9First = StreamChoice.videoTracks(video.videoCandidates, vp9First = true)
        assertEquals("video/avc", avcFirst.first { it.height == 1080 }.codecMime)
        assertTrue(vp9First.all { it.codecMime == StreamChoice.VP9 })
        assertTrue(vp9First.first { it.height == 1080 }.bitrate < avcFirst.first { it.height == 1080 }.bitrate)
        // The adaptive set keeps the codec of the 1080p stream: 4K VP9 is picked by hand on H.264 phones.
        assertTrue(StreamChoice.adaptiveSet(avcFirst).all { it.codecMime == "video/avc" })
        assertEquals(vp9First, StreamChoice.adaptiveSet(vp9First))
    }

    @Test
    fun `DASH manifest lists every quality with its ranges and escaped URLs`() {
        val video = QuickStart.resolved(PlayerResponseParser.parse(response()), "dQw4w9WgXcQ", "c") { true }!!
        val tracks = StreamChoice.adaptiveSet(StreamChoice.videoTracks(video.videoCandidates, vp9First = true))
        assertTrue(YoutubeDash.usable(tracks, video.audio))
        val xml = YoutubeDash.manifest(tracks, video.audio!!, video.durationMs)
        val doc = DocumentBuilderFactory.newInstance().apply { isNamespaceAware = true }.newDocumentBuilder()
            .parse(xml.byteInputStream())
        val mpd = doc.documentElement
        assertEquals("static", mpd.getAttribute("type"))
        assertTrue(mpd.getAttribute("mediaPresentationDuration").startsWith("PT21"))
        val sets = doc.getElementsByTagName("AdaptationSet")
        assertEquals(2, sets.length)
        val reps = doc.getElementsByTagName("Representation")
        assertEquals(tracks.size + 1, reps.length)
        val first = reps.item(0) as org.w3c.dom.Element
        assertEquals("vp9", first.getAttribute("codecs"))
        val base = first.getElementsByTagName("BaseURL").item(0).textContent
        assertTrue(base.startsWith("https://") && base.contains("&itag=") && base.endsWith("&cpn=c"))
        val segment = first.getElementsByTagName("SegmentBase").item(0) as org.w3c.dom.Element
        assertTrue(segment.getAttribute("indexRange").matches(Regex("\\d+-\\d+")))
        val audio = reps.item(reps.length - 1) as org.w3c.dom.Element
        assertEquals("251", audio.getAttribute("id"))
        assertEquals("audio/webm", audio.getAttribute("mimeType"))
        assertFalse(YoutubeDash.usable(tracks, video.audio.copy(ranges = null)))
    }
}
