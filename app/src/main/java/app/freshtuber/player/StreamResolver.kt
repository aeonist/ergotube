/** One playable video quality. */
data class VideoTrack(
    val height: Int,
    val fps: Int,
    val url: String,
    val mimeType: String?,
    val label: String,
    /** Decoder family, e.g. "video/avc"; null when unknown. */
    val codecMime: String? = null,
    val bitrate: Int = 0,
)

data class SubtitleTrack(val url: String, val mimeType: String, val language: String, val label: String, val autoGenerated: Boolean)

/** Everything the player needs, resolved once per video. */
data class ResolvedVideo(
    val videoId: String,
    val title: String,
    val channelName: String?,
    val thumbnailUrl: String?,
    val durationSeconds: Long,
    val isLive: Boolean,
    /** Live streams play through HLS. */
    val hlsUrl: String?,
    /** Every playable video-only stream; [StreamChoice.videoTracks] picks one per quality. */
    val videoCandidates: List<VideoTrack>,
    val audioUrl: String?,
    val audioMimeType: String?,
    /** A combined (video + audio) stream for when separate ones are missing. */
    val muxedUrl: String?,
    val subtitles: List<SubtitleTrack>,
    val channel: ChannelSummary? = null,
)

class NothingPlayableException : Exception("No playable stream")

/**
 * Streams come from NewPipeExtractor: it deciphers YouTube's "n" parameter, so downloads are not
 * throttled. Extraction is anonymous; only an age-restricted video is retried with the account.
 */
@Singleton
class StreamResolver @Inject constructor(
    private val accountCookies: AccountCookieProvider,
) {
    private val anonymous = StreamCache(CoroutineScope(SupervisorJob() + Dispatchers.IO)) { id: String ->
        StreamInfo.getInfo(ServiceList.YouTube, "https://www.youtube.com/watch?v=$id").toResolved(id)
    }

    suspend fun resolve(videoId: String, allowAccount: Boolean = true): ResolvedVideo {
        return try {
            anonymous.get(videoId)
        } catch (e: AgeRestrictedContentException) {
            if (!allowAccount) throw e
            withContext(Dispatchers.IO) {
                accountCookies.withAccountCookies {
                    StreamInfo.getInfo(ServiceList.YouTube, "https://www.youtube.com/watch?v=$videoId").toResolved(videoId)
                }
            }
        }
    }

    fun invalidate(videoId: String) = anonymous.invalidate(videoId)

    private fun StreamInfo.toResolved(videoId: String): ResolvedVideo {
        val live = streamType == StreamType.LIVE_STREAM || streamType == StreamType.AUDIO_LIVE_STREAM
        val video = StreamChoice.candidates(videoOnlyStreams, ::canDecode)
        val audio = StreamChoice.bestAudio(audioStreams)
        val muxed = videoStreams.filter { it.isUrl && it.deliveryMethod == DeliveryMethod.PROGRESSIVE_HTTP }
            .maxByOrNull { it.height }
        if (!live && (video.isEmpty() || audio == null) && muxed == null) throw NothingPlayableException()
        if (live && hlsUrl.isNullOrEmpty()) throw NothingPlayableException()
        val ownerId = uploaderUrl?.substringAfter("/channel/", "")?.substringBefore('?')?.substringBefore('/')
            ?.takeIf { it.matches(Regex("UC[A-Za-z0-9_-]{22}")) }
        return ResolvedVideo(
            videoId = videoId,
            channel = ownerId?.let { id -> uploaderName?.takeIf(String::isNotBlank)?.let { name ->
                ChannelSummary(id, name, uploaderAvatars.maxByOrNull { it.height }?.url)
            } },
            title = name,
            channelName = uploaderName,
            thumbnailUrl = thumbnails.maxByOrNull { it.height }?.url,
            durationSeconds = duration,
            isLive = live,
            hlsUrl = hlsUrl?.takeIf { it.isNotEmpty() },
            videoCandidates = video,
            audioUrl = audio?.content,
            audioMimeType = audio?.format?.mimeType,
            muxedUrl = muxed?.content,
            subtitles = subtitles.filter { it.isUrl }.mapNotNull { sub ->
                val mime = when (sub.format) {
                    MediaFormat.VTT -> "text/vtt"
                    MediaFormat.TTML -> "application/ttml+xml"
                    MediaFormat.SRT -> "application/x-subrip"
                    else -> return@mapNotNull null
                }
                SubtitleTrack(sub.content, mime, sub.languageTag, sub.displayLanguageName, sub.isAutoGenerated)
            }.sortedBy { it.autoGenerated },
        )
    }

    private val decoderCache = HashMap<String, Boolean>()

    /** Whether this device has any decoder for the codec family (AV1 is often missing). */
    private fun canDecode(mimeType: String): Boolean = synchronized(decoderCache) {
        decoderCache.getOrPut(mimeType) {
            MediaCodecList(MediaCodecList.REGULAR_CODECS).codecInfos.any { codec ->
                !codec.isEncoder && codec.supportedTypes.any { it.equals(mimeType, ignoreCase = true) }
            }
        }
    }
}

/** Stream selection rules, pure for tests. */
object StreamChoice {

    /** Progressive video-only streams this device has a decoder for. */
    fun candidates(streams: List<VideoStream>, canDecode: (String) -> Boolean): List<VideoTrack> =
        streams
            .filter { it.isUrl && it.deliveryMethod == DeliveryMethod.PROGRESSIVE_HTTP && it.height > 0 }
            .filter { codecMime(it.codec)?.let(canDecode) ?: true }
            .map {
                VideoTrack(
                    height = it.height,
                    fps = it.fps,
                    url = it.content,
                    mimeType = it.format?.mimeType,
                    label = label(it.height, it.fps),
                    codecMime = codecMime(it.codec),
                    bitrate = it.bitrate,
                )
            }

    /**
     * One track per resolution, best first. Per height: H.264 up to 1080p (efficient hardware
     * decoding everywhere), VP9 above it, AV1 last. Codecs in [blocked] failed on this device.
     */
    fun videoTracks(candidates: List<VideoTrack>, blocked: Set<String> = emptySet()): List<VideoTrack> =
        candidates
            .filter { it.codecMime == null || it.codecMime !in blocked }
            .groupBy { it.height }
            .map { (height, sameHeight) ->
                sameHeight.sortedWith(
                    compareBy<VideoTrack> { codecRank(it.codecMime, height) }
                        .thenByDescending { it.fps }
                        .thenByDescending { it.bitrate },
                ).first()
            }
            .sortedByDescending { it.height }

    /** The original-language track at the highest bitrate, preferring AAC for compatibility. */
    fun bestAudio(streams: List<AudioStream>): AudioStream? =
        streams
            .filter { it.isUrl && it.deliveryMethod == DeliveryMethod.PROGRESSIVE_HTTP }
            .sortedWith(
                compareBy<AudioStream> {
                    when (it.audioTrackType) {
                        null, AudioTrackType.ORIGINAL -> 0
                        else -> 1
                    }
                }.thenByDescending { it.averageBitrate },
            )
            .firstOrNull()

    fun label(height: Int, fps: Int): String = if (fps > 30) "${height}p$fps" else "${height}p"

    /** Index of the track closest to [preferredHeight] without going over it, else the lowest. */
    fun pick(tracks: List<VideoTrack>, preferredHeight: Int): Int {
        if (tracks.isEmpty()) return -1
        val index = tracks.indexOfFirst { it.height <= preferredHeight }
        return if (index >= 0) index else tracks.lastIndex
    }

    private fun codecRank(mime: String?, height: Int): Int = when (mime) {
        "video/avc" -> if (height <= 1080) 0 else 2
        "video/x-vnd.on2.vp9" -> if (height <= 1080) 1 else 0
        "video/av01" -> 3
        else -> 4
    }

    private fun codecMime(codec: String?): String? {
        val c = codec ?: return null
        return when {
            c.startsWith("avc") -> "video/avc"
            c.startsWith("vp9") || c.startsWith("vp09") -> "video/x-vnd.on2.vp9"
            c.startsWith("av01") -> "video/av01"
            else -> null
        }
    }
}
