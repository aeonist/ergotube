/** Where a stream file keeps its header and its index (both ends included). */
data class SegmentRanges(val initStart: Long, val initEnd: Long, val indexStart: Long, val indexEnd: Long) {
    companion object {
        fun of(initStart: Long, initEnd: Long, indexStart: Long, indexEnd: Long): SegmentRanges? =
            if (initEnd > initStart && indexEnd > indexStart && indexStart > initEnd) SegmentRanges(initStart, initEnd, indexStart, indexEnd) else null
    }
}

/** One playable video quality. */
data class VideoTrack(
    val height: Int,
    val fps: Int,
    val url: String,
    val mimeType: String?,
    val label: String,
    /** Decoder family, e.g. "video/avc"; null when unknown. */
    val codecMime: String? = null,
    val bitrate: Int = 0,
    val width: Int = 0,
    val itag: Int = 0,
    /** Full codec string, e.g. "avc1.640028". */
    val codecs: String? = null,
    val ranges: SegmentRanges? = null,
)

/** The audio stream that goes with the video-only ones. */
data class AudioTrack(
    val url: String,
    val mimeType: String?,
    val codecs: String?,
    val bitrate: Int,
    val itag: Int,
    val ranges: SegmentRanges?,
    val sampleRate: Int = 0,
    val channels: Int = 0,
)

data class SubtitleTrack(val url: String, val mimeType: String, val language: String, val label: String, val autoGenerated: Boolean)

/** Everything the player needs, resolved once per video. */
data class ResolvedVideo(
    val videoId: String,
    val title: String,
    val channelName: String?,
    val thumbnailUrl: String?,
    val durationSeconds: Long,
    val isLive: Boolean,
    /** Live streams play through HLS. */
    val hlsUrl: String?,
    /** Every playable video-only stream; [StreamChoice.videoTracks] picks one per quality. */
    val videoCandidates: List<VideoTrack>,
    val audioUrl: String?,
    val audioMimeType: String?,
    /** A combined (video + audio) stream for when separate ones are missing. */
    val muxedUrl: String?,
    val subtitles: List<SubtitleTrack>,
    val channel: ChannelSummary? = null,
    val chapters: List<Chapter> = emptyList(),
    val storyboard: Storyboard? = null,
    /** The audio stream with the details a DASH manifest needs; null for local files. */
    val audio: AudioTrack? = null,
    /** Exact length from the streams when known, else [durationSeconds]. */
    val durationMs: Long = durationSeconds * 1000,
    /** False for the quick start: chapters and the channel picture come later. */
    val complete: Boolean = true,
)

class NothingPlayableException : Exception("No playable stream")

/**
 * Streams come in two steps. First a single `player` request (NewPipeExtractor's visionOS
 * client, the one whose streams it plays), which is all YouTube's own apps need to start:
 * it gives the streams, captions and preview frames. NewPipeExtractor's full extraction
 * makes seven requests one after another (two more players, metadata, related videos), about
 * 1.5 s more before the first byte, so it only runs afterwards for chapters and the channel
 * picture, and as the fallback whenever the quick answer is not plainly playable (age limits,
 * live streams, ciphered or throttled URLs). Extraction is anonymous; only an age-restricted
 * video is retried with the account.
 */
@Singleton
class StreamResolver @Inject constructor(
    private val accountCookies: AccountCookieProvider,
) {
    private val io = CoroutineScope(SupervisorJob() + Dispatchers.IO)
    private val anonymous = StreamCache(io, capacity = 6) { id: String ->
        val quick = try { quick(id) } catch (e: kotlinx.coroutines.CancellationException) { throw e } catch (e: Exception) {
            if (app.freshtuber.BuildConfig.DEBUG) android.util.Log.d("StreamResolver", "quick start unavailable: ${e.javaClass.simpleName}")
            null
        }
        quick ?: full(id)
    }
    /** The complete extraction, for chapters and the channel picture once playback runs. */
    private val complete = StreamCache(io, capacity = 2) { id: String -> full(id) }

    private fun full(id: String): ResolvedVideo =
        StreamInfo.getInfo(ServiceList.YouTube, "https://www.youtube.com/watch?v=$id").toResolved(id)

    private val visionOs = VisionOsPlayer()

    init {
        // Fetch the visitor id while the user is still choosing a video.
        io.launch { runCatching { visionOs.visitorData() } }
    }

    /** A single player request (visitor id cached); null when the full extraction must decide. */
    private fun quick(id: String): ResolvedVideo? {
        val cpn = YoutubeParsingHelper.generateContentPlaybackNonce()
        val raw = visionOs.player(id, cpn)
        val json = kotlinx.serialization.json.Json.parseToJsonElement(com.grack.nanojson.JsonWriter.string(raw)) as kotlinx.serialization.json.JsonObject
        val parsed = PlayerResponseParser.parse(json)
        // A bot check or odd answer may come from a stale visitor id: get a new one next time.
        if (parsed.status != "OK") visionOs.forget()
        return QuickStart.resolved(parsed, id, cpn, ::canDecode).also {
            if (it == null && app.freshtuber.BuildConfig.DEBUG) android.util.Log.d("StreamResolver",
                "quick start declined: status=${parsed.status} live=${parsed.isLive} formats=${parsed.adaptive.size} " +
                    "ciphered=${parsed.adaptive.count { f -> f.ciphered }} throttled=${parsed.adaptive.count { f -> f.url?.contains("&n=") == true }}")
        }
    }

    /** Chapters, the channel picture and anything the quick answer lacked. */
    suspend fun completed(video: ResolvedVideo): ResolvedVideo {
        if (video.complete) return video
        return complete.get(video.videoId)
    }

    suspend fun resolve(videoId: String, allowAccount: Boolean = true): ResolvedVideo {
        return try {
            anonymous.get(videoId)
        } catch (e: AgeRestrictedContentException) {
            if (!allowAccount) throw e
            withContext(Dispatchers.IO) {
                accountCookies.withAccountCookies {
                    StreamInfo.getInfo(ServiceList.YouTube, "https://www.youtube.com/watch?v=$videoId").toResolved(videoId)
                }
            }
        }
    }

    fun invalidate(videoId: String) { anonymous.invalidate(videoId); complete.invalidate(videoId) }

    private fun StreamInfo.toResolved(videoId: String): ResolvedVideo {
        val live = streamType == StreamType.LIVE_STREAM || streamType == StreamType.AUDIO_LIVE_STREAM
        val video = StreamChoice.candidates(videoOnlyStreams, ::canDecode)
        val audio = StreamChoice.bestAudio(audioStreams)
        val streamMs = (videoOnlyStreams + audioStreams).mapNotNull { it.itagItem?.approxDurationMs?.takeIf { ms -> ms > 0 } }.maxOrNull()
        val muxed = videoStreams.filter { it.isUrl && it.deliveryMethod == DeliveryMethod.PROGRESSIVE_HTTP }
            .maxByOrNull { it.height }
        if (!live && (video.isEmpty() || audio == null) && muxed == null) throw NothingPlayableException()
        if (live && hlsUrl.isNullOrEmpty()) throw NothingPlayableException()
        val ownerId = uploaderUrl?.substringAfter("/channel/", "")?.substringBefore('?')?.substringBefore('/')
            ?.takeIf { it.matches(Regex("UC[A-Za-z0-9_-]{22}")) }
        return ResolvedVideo(
            videoId = videoId,
            channel = ownerId?.let { id -> uploaderName?.takeIf(String::isNotBlank)?.let { name ->
                ChannelSummary(id, name, uploaderAvatars.maxByOrNull { it.height }?.url)
            } },
            title = name,
            channelName = uploaderName,
            thumbnailUrl = thumbnails.maxByOrNull { it.height }?.url,
            durationSeconds = duration,
            isLive = live,
            hlsUrl = hlsUrl?.takeIf { it.isNotEmpty() },
            videoCandidates = video,
            audioUrl = audio?.content,
            audioMimeType = audio?.format?.mimeType,
            audio = audio?.let {
                AudioTrack(it.content, it.format?.mimeType, it.codec, it.bitrate.takeIf { b -> b > 0 } ?: (it.averageBitrate * 1000), it.itag,
                    SegmentRanges.of(it.initStart.toLong(), it.initEnd.toLong(), it.indexStart.toLong(), it.indexEnd.toLong()),
                    it.itagItem?.sampleRate ?: 0, it.itagItem?.audioChannels ?: 0)
            },
            durationMs = streamMs ?: duration * 1000,
            muxedUrl = muxed?.content,
            subtitles = subtitles.filter { it.isUrl }.mapNotNull { sub ->
                val mime = when (sub.format) {
                    MediaFormat.VTT -> "text/vtt"
                    MediaFormat.TTML -> "application/ttml+xml"
                    MediaFormat.SRT -> "application/x-subrip"
                    else -> return@mapNotNull null
                }
                SubtitleTrack(sub.content, mime, sub.languageTag, sub.displayLanguageName, sub.isAutoGenerated)
            }.sortedBy { it.autoGenerated },
            chapters = Chapter.normalized(streamSegments.orEmpty().map { Chapter(it.startTimeSeconds.toLong(), it.title.orEmpty()) }, duration),
            storyboard = Storyboard.pick(previewFrames.orEmpty().map {
                Storyboard(it.urls, it.totalCount, it.framesPerPageX, it.framesPerPageY, it.frameWidth, it.frameHeight, it.durationPerFrame)
            }),
        )
    }

    private fun canDecode(mimeType: String): Boolean = Decoders.any(mimeType)
}

/**
 * NewPipeExtractor's visionOS `player` request (YoutubeStreamHelper.getVisionOsPlayerResponse,
 * v0.26.5) without its visitor-data request before every video: the visitor id lives for hours,
 * so it is fetched once, ahead of time, and reused. Same URL, headers and body as the original.
 */
private class VisionOsPlayer {
    private val lock = Any()
    @Volatile private var visitor: String? = null
    @Volatile private var fetchedAt = 0L

    private fun headers() = mapOf(
        "User-Agent" to listOf(YoutubeParsingHelper.getVisionOsUserAgent(NewPipe.getPreferredLocalization())),
        "X-Goog-Api-Format-Version" to listOf("2"),
    )

    fun visitorData(): String = synchronized(lock) {
        visitor?.takeIf { System.currentTimeMillis() - fetchedAt < MAX_AGE_MS }?.let { return it }
        val client = org.schabi.newpipe.extractor.services.youtube.InnertubeClientRequestInfo.ofVisionOsClient()
        YoutubeParsingHelper.getVisitorDataFromInnertube(client, NewPipe.getPreferredLocalization(), NewPipe.getPreferredContentCountry(),
            headers(), "https://www.youtube.com/youtubei/v1/", null, false).also { visitor = it; fetchedAt = System.currentTimeMillis() }
    }

    fun forget() { visitor = null }

    fun player(videoId: String, cpn: String): com.grack.nanojson.JsonObject {
        val localization = NewPipe.getPreferredLocalization()
        val client = org.schabi.newpipe.extractor.services.youtube.InnertubeClientRequestInfo.ofVisionOsClient()
        client.clientInfo.visitorData = visitorData()
        val body = YoutubeParsingHelper.prepareJsonBuilder(localization, NewPipe.getPreferredContentCountry(), client, null)
            .value("videoId", videoId).value("cpn", cpn).value("contentCheckOk", true).value("racyCheckOk", true)
            .done()
        val url = "https://youtubei.googleapis.com/youtubei/v1/player?prettyPrint=false&t=${YoutubeParsingHelper.generateTParameter()}&id=$videoId"
        return try {
            val response = NewPipe.getDownloader().postWithContentTypeJson(url, headers(),
                com.grack.nanojson.JsonWriter.string(body).toByteArray(Charsets.UTF_8), localization)
            org.schabi.newpipe.extractor.utils.JsonUtils.toJsonObject(YoutubeParsingHelper.getValidJsonResponseBody(response))
        } catch (e: Exception) { forget(); throw e }
    }

    companion object { const val MAX_AGE_MS = 3 * 60 * 60 * 1000L }
}

/** What this device can decode, asked once per codec family. */
object Decoders {
    private val any = HashMap<String, Boolean>()
    private val hardware = HashMap<String, Boolean>()

    /** Whether this device has any decoder for the codec family (AV1 is often missing). */
    fun any(mimeType: String): Boolean = synchronized(any) {
        any.getOrPut(mimeType) { decoders(mimeType).isNotEmpty() }
    }

    /** Whether a hardware decoder handles the family, so it is cheap on the battery. */
    fun hardware(mimeType: String): Boolean = synchronized(hardware) {
        hardware.getOrPut(mimeType) {
            decoders(mimeType).any { codec ->
                if (android.os.Build.VERSION.SDK_INT >= 29) codec.isHardwareAccelerated && !codec.isSoftwareOnly
                else !codec.name.startsWith("OMX.google.") && !codec.name.startsWith("c2.android.")
            }
        }
    }

    private fun decoders(mimeType: String) = runCatching {
        MediaCodecList(MediaCodecList.REGULAR_CODECS).codecInfos.filter { codec ->
            !codec.isEncoder && codec.supportedTypes.any { it.equals(mimeType, ignoreCase = true) }
        }
    }.getOrDefault(emptyList())
}

/** Turns the quick `player` answer into streams, or null when it is not plainly playable. */
object QuickStart {
    fun resolved(response: PlayerResponse, videoId: String, cpn: String, canDecode: (String) -> Boolean): ResolvedVideo? {
        if (response.status != "OK" || response.isLive || response.isUpcoming) return null
        if (response.videoId != null && response.videoId != videoId) return null
        // A URL that is ciphered or carries the throttling parameter needs the full extraction.
        fun playable(format: PlayerFormat) = !format.otf && !format.ciphered && format.url != null &&
            !Regex("[?&]n=").containsMatchIn(format.url)
        // NewPipeExtractor adds the playback nonce to every stream URL the same way.
        fun url(format: PlayerFormat) = format.url + "&cpn=" + cpn
        fun ranges(format: PlayerFormat) = format.initRange?.let { init -> format.indexRange?.let { index ->
            SegmentRanges.of(init.start, init.end, index.start, index.end) } }
        val video = response.adaptive.filter { it.isVideo && it.height > 0 && playable(it) }
            .mapNotNull { format ->
                val family = StreamChoice.codecMime(format.codecs)
                if (family != null && !canDecode(family)) return@mapNotNull null
                VideoTrack(format.height, format.fps, url(format), format.mimeType, StreamChoice.label(format.height, format.fps),
                    family, format.bitrate, format.width, format.itag, format.codecs, ranges(format))
            }
        // The original-language track (dubbed and described ones are not default), highest peak
        // bitrate: Opus 251 over AAC 140 at about the same average, as NewPipeExtractor ranks them.
        val audioFormat = response.adaptive.filter { it.isAudio && playable(it) }
            .sortedWith(compareBy<PlayerFormat> { if (it.audioIsDefault == false) 1 else 0 }.thenByDescending { it.bitrate })
            .firstOrNull()
        val muxed = response.muxed.filter { playable(it) && it.height > 0 }.maxByOrNull { it.height }
        if ((video.isEmpty() || audioFormat == null) && muxed == null) return null
        val streamMs = (response.adaptive).mapNotNull { it.approxDurationMs?.takeIf { ms -> ms > 0 } }.maxOrNull()
        return ResolvedVideo(
            videoId = videoId,
            title = response.title.orEmpty(),
            channelName = response.author,
            thumbnailUrl = response.thumbnailUrl,
            durationSeconds = response.lengthSeconds,
            isLive = false,
            hlsUrl = null,
            videoCandidates = video,
            audioUrl = audioFormat?.let(::url),
            audioMimeType = audioFormat?.mimeType,
            muxedUrl = muxed?.let(::url),
            subtitles = response.captions.map { caption ->
                // As NewPipeExtractor offers them: TTML, which Media3 parses during extraction.
                val base = caption.baseUrl.replace(Regex("&fmt=[^&]*"), "")
                SubtitleTrack("$base&fmt=ttml", "application/ttml+xml", caption.languageCode,
                    caption.name ?: caption.languageCode, caption.autoGenerated)
            }.sortedBy { it.autoGenerated },
            channel = response.channelId?.takeIf { it.matches(Regex("UC[A-Za-z0-9_-]{22}")) }?.let { id ->
                response.author?.takeIf(String::isNotBlank)?.let { ChannelSummary(id, it, null) }
            },
            storyboard = Storyboard.pick(response.storyboards),
            audio = audioFormat?.let {
                AudioTrack(url(it), it.mimeType, it.codecs, it.bitrate, it.itag, ranges(it), it.audioSampleRate, it.audioChannels)
            },
            durationMs = streamMs ?: response.lengthSeconds * 1000,
            complete = false,
        )
    }
}

/** Stream selection rules, pure for tests. */
object StreamChoice {

    /** Progressive video-only streams this device has a decoder for. */
    fun candidates(streams: List<VideoStream>, canDecode: (String) -> Boolean): List<VideoTrack> =
        streams
            .filter { it.isUrl && it.deliveryMethod == DeliveryMethod.PROGRESSIVE_HTTP && it.height > 0 }
            .filter { codecMime(it.codec)?.let(canDecode) ?: true }
            .map {
                VideoTrack(
                    height = it.height,
                    fps = it.fps,
                    url = it.content,
                    mimeType = it.format?.mimeType,
                    label = label(it.height, it.fps),
                    codecMime = codecMime(it.codec),
                    bitrate = it.bitrate,
                    width = it.width,
                    itag = it.itag,
                    codecs = it.codec,
                    ranges = SegmentRanges.of(it.initStart.toLong(), it.initEnd.toLong(), it.indexStart.toLong(), it.indexEnd.toLong()),
                )
            }

    /**
     * One track per resolution, best first. Per height: H.264 up to 1080p (efficient hardware
     * decoding everywhere), VP9 above it, AV1 last. With [vp9First] (a hardware VP9 decoder, as
     * on Pixels) VP9 at every height, as YouTube's app does: about a third fewer bytes for the
     * same picture, so videos start and buffer faster. Codecs in [blocked] failed on this device.
     */
    fun videoTracks(candidates: List<VideoTrack>, blocked: Set<String> = emptySet(), vp9First: Boolean = false): List<VideoTrack> =
        candidates
            .filter { it.codecMime == null || it.codecMime !in blocked }
            .groupBy { it.height }
            .map { (height, sameHeight) ->
                sameHeight.sortedWith(
                    compareBy<VideoTrack> { if (vp9First && it.codecMime == VP9) -1 else codecRank(it.codecMime, height) }
                        .thenByDescending { it.fps }
                        .thenByDescending { it.bitrate },
                ).first()
            }
            .sortedByDescending { it.height }

    /** The original-language track at the highest bitrate, preferring AAC for compatibility. */
    fun bestAudio(streams: List<AudioStream>): AudioStream? =
        streams
            .filter { it.isUrl && it.deliveryMethod == DeliveryMethod.PROGRESSIVE_HTTP }
            .sortedWith(
                compareBy<AudioStream> {
                    when (it.audioTrackType) {
                        null, AudioTrackType.ORIGINAL -> 0
                        else -> 1
                    }
                }.thenByDescending { it.averageBitrate },
            )
            .firstOrNull()

    const val VP9 = "video/x-vnd.on2.vp9"

    /**
     * The tracks the player adapts between on its own: those of the codec used up to 1080p
     * (switching codecs mid-video would restart the decoder). Others are picked by hand.
     */
    fun adaptiveSet(tracks: List<VideoTrack>): List<VideoTrack> {
        val family = (tracks.firstOrNull { it.height <= 1080 } ?: tracks.lastOrNull())?.codecMime ?: return emptyList()
        return tracks.filter { it.codecMime == family }
    }

    fun label(height: Int, fps: Int): String = if (fps > 30) "${height}p$fps" else "${height}p"

    /** Index of the track closest to [preferredHeight] without going over it, else the lowest. */
    fun pick(tracks: List<VideoTrack>, preferredHeight: Int): Int {
        if (tracks.isEmpty()) return -1
        val index = tracks.indexOfFirst { it.height <= preferredHeight }
        return if (index >= 0) index else tracks.lastIndex
    }

    private fun codecRank(mime: String?, height: Int): Int = when (mime) {
        "video/avc" -> if (height <= 1080) 0 else 2
        "video/x-vnd.on2.vp9" -> if (height <= 1080) 1 else 0
        "video/av01" -> 3
        else -> 4
    }

    fun codecMime(codec: String?): String? {
        val c = codec ?: return null
        return when {
            c.startsWith("avc") -> "video/avc"
            c.startsWith("vp9") || c.startsWith("vp09") -> "video/x-vnd.on2.vp9"
            c.startsWith("av01") -> "video/av01"
            else -> null
        }
    }
}
