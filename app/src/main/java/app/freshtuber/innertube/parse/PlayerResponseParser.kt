/** A byte range inside a stream file, both ends included. */
data class ByteRange(val start: Long, val end: Long)

/** One stream from a player response's `streamingData`. */
data class PlayerFormat(
    val itag: Int,
    val url: String?,
    /** Container type, e.g. "video/mp4" or "audio/webm". */
    val mimeType: String,
    /** Codec string from the mime type, e.g. "avc1.640028", "vp9", "opus". */
    val codecs: String?,
    val bitrate: Int,
    val averageBitrate: Int,
    val width: Int,
    val height: Int,
    val fps: Int,
    val initRange: ByteRange?,
    val indexRange: ByteRange?,
    val contentLength: Long?,
    val approxDurationMs: Long?,
    val audioSampleRate: Int,
    val audioChannels: Int,
    /** Null for a single-language video; false for a dubbed or described track. */
    val audioIsDefault: Boolean?,
    /** Live-like "on the fly" streams that have no index and need a different player. */
    val otf: Boolean,
    /** Ciphered formats carry no direct URL. */
    val ciphered: Boolean,
) {
    val isVideo: Boolean get() = mimeType.startsWith("video/")
    val isAudio: Boolean get() = mimeType.startsWith("audio/")
}

data class PlayerCaption(val baseUrl: String, val languageCode: String, val name: String?, val autoGenerated: Boolean)

/** What a `player` response says about a video, enough to start playing it. */
data class PlayerResponse(
    val status: String?,
    val reason: String?,
    val videoId: String?,
    val title: String?,
    val author: String?,
    val channelId: String?,
    val lengthSeconds: Long,
    val isLive: Boolean,
    val isUpcoming: Boolean,
    val thumbnailUrl: String?,
    val adaptive: List<PlayerFormat>,
    val muxed: List<PlayerFormat>,
    val hlsManifestUrl: String?,
    val captions: List<PlayerCaption>,
    val storyboards: List<Storyboard>,
)

/**
 * Reads InnerTube `player` responses (`playabilityStatus`, `streamingData`, `videoDetails`,
 * `captions`, `storyboards`). Field names and the storyboard spec follow NewPipeExtractor's
 * YoutubeStreamExtractor and yt-dlp.
 */
object PlayerResponseParser {

    fun parse(root: JsonObject): PlayerResponse {
        val details = root.obj("videoDetails")
        val streaming = root.obj("streamingData")
        return PlayerResponse(
            status = root.path("playabilityStatus").str("status"),
            reason = root.path("playabilityStatus").str("reason"),
            videoId = details.str("videoId"),
            title = details.str("title"),
            author = details.str("author"),
            channelId = details.str("channelId"),
            lengthSeconds = details.long("lengthSeconds") ?: 0L,
            isLive = details.bool("isLive") == true || root.path("playabilityStatus", "liveStreamability") != null,
            isUpcoming = details.bool("isUpcoming") == true,
            thumbnailUrl = details.obj("thumbnail").bestThumbnailUrl(),
            adaptive = streaming.arr("adaptiveFormats").orEmpty().mapNotNull { (it as? JsonObject)?.let(::format) },
            muxed = streaming.arr("formats").orEmpty().mapNotNull { (it as? JsonObject)?.let(::format) },
            hlsManifestUrl = streaming.str("hlsManifestUrl"),
            captions = root.path("captions", "playerCaptionsTracklistRenderer").arr("captionTracks").orEmpty().mapNotNull { track ->
                val url = track.str("baseUrl") ?: return@mapNotNull null
                val language = track.str("languageCode") ?: return@mapNotNull null
                PlayerCaption(url, language, track.obj("name").text(), track.str("kind") == "asr")
            },
            storyboards = storyboards(root.path("storyboards", "playerStoryboardSpecRenderer").str("spec")),
        )
    }

    private fun format(json: JsonObject): PlayerFormat? {
        val itag = json.int("itag") ?: return null
        val type = json.str("mimeType") ?: return null
        return PlayerFormat(
            itag = itag,
            url = json.str("url"),
            mimeType = type.substringBefore(';').trim(),
            codecs = Regex("codecs=\"([^\"]+)\"").find(type)?.groupValues?.get(1),
            bitrate = json.int("bitrate") ?: 0,
            averageBitrate = json.int("averageBitrate") ?: json.int("bitrate") ?: 0,
            width = json.int("width") ?: 0,
            height = json.int("height") ?: 0,
            fps = json.int("fps") ?: 0,
            initRange = range(json.obj("initRange")),
            indexRange = range(json.obj("indexRange")),
            contentLength = json.long("contentLength"),
            approxDurationMs = json.long("approxDurationMs"),
            audioSampleRate = json.int("audioSampleRate") ?: 0,
            audioChannels = json.int("audioChannels") ?: 0,
            audioIsDefault = json.obj("audioTrack").bool("audioIsDefault"),
            otf = json.str("type") == "FORMAT_STREAM_TYPE_OTF",
            ciphered = json.str("url") == null && (json.str("signatureCipher") != null || json.str("cipher") != null),
        )
    }

    private fun range(json: JsonObject?): ByteRange? {
        val start = json.long("start") ?: return null
        val end = json.long("end") ?: return null
        return if (end >= start) ByteRange(start, end) else null
    }

    /**
     * The spec is "base|level0|level1|…"; each level is "width#height#count#columns#rows#interval#name#sigh".
     * The base URL has `$L` (level), `$N` (name) and the name may hold `$M` (page). Levels without
     * an interval are skipped, as NewPipeExtractor does.
     */
    fun storyboards(spec: String?): List<Storyboard> {
        val parts = spec?.split('|') ?: return emptyList()
        if (parts.size < 2) return emptyList()
        val base = parts[0]
        return (1 until parts.size).mapNotNull { level ->
            val p = parts[level].split('#')
            if (p.size != 8) return@mapNotNull null
            val width = p[0].toIntOrNull() ?: return@mapNotNull null
            val height = p[1].toIntOrNull() ?: return@mapNotNull null
            val count = p[2].toIntOrNull() ?: return@mapNotNull null
            val columns = p[3].toIntOrNull() ?: return@mapNotNull null
            val rows = p[4].toIntOrNull() ?: return@mapNotNull null
            val interval = p[5].toIntOrNull() ?: return@mapNotNull null
            if (interval == 0 || columns <= 0 || rows <= 0) return@mapNotNull null
            val url = base.replace("\$L", (level - 1).toString()).replace("\$N", p[6]) + "&sigh=" + p[7]
            val urls = if ("\$M" in url) {
                val pages = (count + columns * rows - 1) / (columns * rows)
                (0 until pages).map { url.replace("\$M", it.toString()) }
            } else listOf(url)
            Storyboard(urls, count, columns, rows, width, height, interval)
        }
    }

    private fun kotlinx.serialization.json.JsonElement?.long(key: String): Long? =
        ((this as? JsonObject)?.get(key) as? JsonPrimitive)?.contentOrNull?.toLongOrNull()
}
